"""Build the profile: python scripts/build.py [panel ...]   (no args = everything)."""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import content as C  # noqa: E402
import panels  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets"


def targets():
    yield "hero", panels.hero
    yield "btn-work", lambda: panels.button("View my work", True)
    yield "btn-contact", lambda: panels.button("Get in touch", False, "mail")
    yield "marquee", panels.marquee
    yield "about", panels.about
    yield "toolkit", panels.toolkit
    yield "work", panels.work_header
    yield "project-radar", panels.featured
    for p, doc in zip(C.PRODUCTS, panels.products()):
        yield f"project-{p['key']}", (lambda doc=doc: doc)
    for p, doc in zip(C.REPOS, panels.repos()):
        yield f"repo-{p['num']}", (lambda doc=doc: doc)
    yield "experience", panels.experience
    yield "contact", panels.contact
    for icon, label, value, _ in C.CHANNELS:
        yield f"channel-{label.lower()}", (lambda i=icon, l=label, v=value: panels.channel(i, l, v))
    yield "footer", panels.footer


def img(src, alt, width="100%", height=None):
    size = f'height="{height}"' if height else f'width="{width}"'
    return f'<img src="assets/{src}.svg" {size} alt="{alt}">'


def link(href, inner):
    return f'<a href="{href}">{inner}</a>'


def readme() -> str:
    pf = C.PORTFOLIO
    rows = [
        link(pf, img("hero", f"{C.NAME} — {C.ROLE}, {C.LOCATION}. {C.INTRO}")),
        link(pf, img("btn-work", "View my work", height=52)) + "\n" + link("mailto:" + C.EMAIL, img("btn-contact", "Get in touch", height=52)),
        link(pf, img("marquee", "Toolkit: " + ", ".join(C.MARQUEE_TOOLS))),
        link(pf + "/#about", img("about", "About: " + " ".join(p.replace("**", "") for p in C.ABOUT))),
        link(pf + "/#about", img("toolkit", "Toolkit — " + "; ".join(f"{t}: {', '.join(i)}" for _, t, _, i in C.TOOLKIT))),
        link(f"https://github.com/{C.LOGIN}?tab=repositories", img("work", "Selected work")),
        link(C.FEATURED["href"], img("project-radar", f"{C.FEATURED['title']}: {C.FEATURED['text']}")),
        " ".join(link(p["href"], img(f"project-{p['key']}", f"{p['title']}: {p['text']}", "49.5%")) for p in C.PRODUCTS),
    ]
    for pair in (C.REPOS[0:2], C.REPOS[2:4]):
        rows.append(" ".join(link(f"https://github.com/{C.LOGIN}/{p['repo']}", img(f"repo-{p['num']}", f"{p['title']}: {p['text']}", "49.5%")) for p in pair))
    rows += [
        link(pf + "/#experience", img("experience", "Experience: " + "; ".join(f"{e['title']}, {e['org']}" for e in C.EXPERIENCE))),
        link("mailto:" + C.EMAIL, img("contact", "Let's build something intelligent. " + C.CONTACT_TEXT)),
    ]
    ch = [link(href, img(f"channel-{label.lower()}", f"{label}: {value}", "49.5%")) for _, label, value, href in C.CHANNELS]
    rows += [" ".join(ch[0:2]), " ".join(ch[2:4])]
    rows.append(link(pf, img("footer", f"© {C.NAME} · {C.ROLE} · {C.LOCATION}")))
    return "<!-- Generated by scripts/build.py — edit scripts/content.py, then run: python scripts/build.py -->\n\n" + "\n\n".join(rows) + "\n"


def main(argv):
    ASSETS.mkdir(exist_ok=True)
    wanted = set(argv)
    for name, make in targets():
        if wanted and name not in wanted:
            continue
        doc = make()
        if doc is None:
            continue
        size = doc.save(ASSETS / f"{name}.svg")
        print(f"{name:20s} {doc.w:>4}×{doc.h:<4} {size / 1024:7.1f} KB")
    if not wanted or "readme" in wanted:
        (ROOT / "README.md").write_text(readme(), encoding="utf-8")
        print("README.md")


if __name__ == "__main__":
    main(sys.argv[1:])
